 'use strict';
const assert=require('node:assert/strict');
const E=require('../dist/engine.js');
const S=require('../dist/school-systems.js');
const M=require('../dist/major-systems.js');
const create=seed=>{const s=E.create('패치 검증',seed,{gender:'male'});E.setClubs(s,'physics','none');return s;};
const clamp=(n,a=0,b=100)=>Math.max(a,Math.min(b,n));
const api=S.createAPI({rng:()=>0.5,clamp,round:n=>Math.round(n*100)/100,shift:(s,updates)=>{for(const [k,v] of Object.entries(updates))s.stats[k]=(s.stats[k]||0)+v;},note:()=>{},assertAlive:()=>{}});
const student=create(4411); api.init(student);
assert.equal(E.EXAM_SHAPE[5].ms[0],81.3,'Last-term math/science becomes slightly harder');
assert.equal(E.EXAM_SHAPE[5].gen[0],84.9,'Last-term general subjects become slightly harder');
assert.equal(E.getMajorOptions(student).length,13);
assert.ok(E.getMajorOptions(student).every(m=>m.unlocked),'Missing courses never lock an application');
assert.ok(E.getMajorOptions(student).find(m=>m.id==='physics').fitScore<0,'Missing relevant courses incur document-review penalty');
assert.ok(E.getMajorOptions(student).find(m=>m.id==='general').fitScore===0);
const credit=api.grantOlympiadFieldCredit(student,'수학');
assert.equal(credit.credits,1);
assert.equal(api.getFieldStatus(student).independentCredits,1);
assert.equal(api.grantOlympiadFieldCredit(student,'물리'),null,'Only one independent field credit');
const withBasic=structuredClone(student);withBasic.school.fieldCredits=[];
assert.ok(api.getFieldStatus(withBasic).canIndependent);
const oldRoll={qualified:true,subjectId:'math',subjectName:'수학',turn:11,year:1};
const events=api.nationalTeamEvents(withBasic,oldRoll);
assert.equal(events.length,1);
assert.equal(events[0].choices.length,3);
assert.match(events[0].title,/수학/);
const rec=withBasic.school.nationalTeam.at(-1);
assert.equal(rec.stage,'invited');
assert.ok(!rec.selected);
const round2=api.resolve(withBasic,events[0],events[0].choices[0]);
assert.equal(round2.events.length,1);
assert.equal(rec.stage,'trained');
assert.equal(round2.events[0].id,'school_national_selection');
const round3=api.resolve(withBasic,round2.events[0],round2.events[0].choices[0]);
assert.ok(rec.chance <= 0.075,'National selection remains extremely selective');
assert.ok(round3.handled);
assert.ok(['selected','not_selected'].includes(rec.stage));
// The second-year optional popup is scheduled for week 2 of 2-2.
const second=create(4422);second.turn=22;
const scheduled=E.getPhase(second);
assert.equal(scheduled.year,2);assert.equal(scheduled.semester,2);
const earlyConfirm=E.create('지원 테스트',4545,{gender:'female'});
assert.equal(E.canEnroll(earlyConfirm,{id:'kaist',accepted:true,earlyAdmissionApproved:true}),null);
console.log('v14.11 admissions, courses, olympiad, field-credit, national-selection checks passed');
